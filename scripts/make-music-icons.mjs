// Regenerates src/renderer/features/pods/musicIcons.ts from simple-icons.
//
// The music picker needs a mark for each service BEFORE the Pod exists, so the
// favicon the Pod would report later is no help. These are the official brand
// marks, taken as plain path data the same way src/overlay/icons.ts takes
// Lucide's, so nothing is imported at runtime and nothing is fetched.
//
// Run after bumping simple-icons:  bun scripts/make-music-icons.mjs
//
// simple-icons is CC0-1.0; the marks themselves remain the trademarks of their
// owners and are used here only to identify the service being offered.

import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import {
  siApplemusic,
  siBandcamp,
  siDeezer,
  siSoundcloud,
  siTidal,
  siYoutube,
  siYoutubemusic
} from 'simple-icons'

// Keyed by the URL in MUSIC_SITES, which is the stable identifier: the display
// names are wording and have already changed once.
const BY_URL = {
  'https://music.youtube.com/': siYoutubemusic,
  'https://www.youtube.com/': siYoutube,
  'https://soundcloud.com/': siSoundcloud,
  'https://www.deezer.com/': siDeezer,
  'https://music.apple.com/': siApplemusic,
  'https://listen.tidal.com/': siTidal,
  'https://bandcamp.com/': siBandcamp
}

const entries = Object.entries(BY_URL)
  .map(
    ([url, icon]) =>
      `  '${url}': {
    hex: '#${icon.hex}',
    path: '${icon.path}'
  }`
  )
  .join(',\n')

const out = `/**
 * Official brand marks for the music services, as plain path data.
 *
 * GENERATED by scripts/make-music-icons.mjs from simple-icons. Do not edit by
 * hand; re-run the script instead.
 *
 * Kept as data rather than imported for the same reason src/overlay/icons.ts
 * is: the eight paths this picker shows cost a few hundred bytes inlined,
 * while the package they come from is not something to ship or to load at
 * startup. Nothing here is fetched either, so the picker draws the same with
 * no network.
 *
 * \`hex\` is the brand's own colour and is used as given. Some are near-black
 * (Tidal), which the dark picker cannot show, so the component lightens those
 * rather than storing a colour the brand does not use.
 *
 * simple-icons is CC0-1.0; the marks remain the trademarks of their owners and
 * identify the service being offered, nothing more.
 */

export interface BrandMark {
  /** The brand's own colour, '#RRGGBB'. */
  hex: string
  /** Single path, drawn in a 24x24 viewBox. */
  path: string
}

export const MUSIC_MARKS: Record<string, BrandMark> = {
${entries}
}
`

writeFileSync(join('src', 'renderer', 'features', 'pods', 'musicIcons.ts'), out, 'utf-8')
console.log(`[make-music-icons] wrote ${entries.split('},\n').length} marks`)
